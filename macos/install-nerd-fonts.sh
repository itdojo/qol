main() {
    banner "NERD FONTS" "macos · homebrew casks"

    log_phase "PREFLIGHT"
    if [[ "$(uname -s)" != "Darwin" ]]; then
        log_err "This script is macOS-only (it installs fonts with Homebrew casks)."
        exit 1
    fi
    if ! command -v brew >/dev/null 2>&1; then
        log_err "Homebrew is required. Install it from https://brew.sh and re-run."
        exit 1
    fi
    log_ok "macOS with Homebrew. ${#FONTS[@]} fonts queued."

    log_phase "FONTS"
    local failed=() font
    for font in "${FONTS[@]}"; do
        if brew list --cask "$font" >/dev/null 2>&1; then
            log_ok "$font is already installed."
            continue
        fi
        log_step "Installing $font..."
        if brew install --cask "$font"; then
            log_ok "$font is installed."
        else
            log_warn "$font failed to install; continuing with the rest."
            failed+=("$font")
        fi
    done

    if (( ${#failed[@]} > 0 )); then
        log_warn "These fonts failed to install: ${failed[*]}"
        log_complete "NERD FONTS INSTALLED WITH ERRORS"
        log_next "Retry the failures:  brew install --cask ${failed[*]}"
        log_next "Or check the cask names against  brew search nerd-font"
        echo
        exit 1
    fi

    log_complete "NERD FONTS INSTALLED"
    log_next "Set your terminal font to one of the installed families."
    log_next "For a Powerlevel10k prompt, that font is 'MesloLGS NF'."
    echo
}

main "$@"
